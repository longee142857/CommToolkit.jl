    esn0_db::Float64
    n_blocks::Int
    n_ack::Int
    n_delivered::Int
    n_undetected::Int
    n_success_bits::Int
    n_bit_errors::Int
    n_payload_bits::Int
    n_channel_uses::Int
    n_transmissions::Int
    ber::Float64
    bler::Float64
    throughput::Float64
    spectral_efficiency::Float64
    mean_mcs_efficiency::Float64
    mean_transmissions::Float64
    mcs_histogram::Vector{Int}
    mcs_names::Vector{String}
end

