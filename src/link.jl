function _channel_llr(symbols, esn0_db::Float64, scheme::ModulationScheme, approx::Symbol)
    # Es/N0 = +∞ has σ² = 0, which demodulate_soft rejects. The hard decision
    # is exact; a finite LLR with the right sign is enough for both decoders.
    if esn0_db == Inf
        hard = demodulate(symbols, scheme)
        return _NOISELESS_LLR .* (1 .- 2 .* Float64.(hard))
    end
    noise_var = inv(2 * snr_db_to_linear(esn0_db))
    return demodulate_soft(symbols, scheme, noise_var; approx=approx)
end

function _encode(mcs::MCS, info::Vector{Int})
    if mcs.family === :convolutional
        return conv_encode(info)
    end
    return ldpc_encode(mcs.ldpc, info)
end

function _decode_info(mcs::MCS, llr::Vector{Float64}, max_iter::Int, algorithm::Symbol)
    if mcs.family === :convolutional
        return viterbi_decode(llr)
    end
    return ldpc_decode(mcs.ldpc, llr; algorithm=algorithm, max_iter=max_iter)
end

function _payload_errors(payload::Vector{Int}, decoded::Vector{Int}, n_info::Int)
    if length(decoded) != n_info
        return length(payload)
    end
    k = 0
    @inbounds for i in eachindex(payload)
        k += payload[i] != decoded[i]
    end
    return k
end

"""Push one linear Es/N0 sample into a circular buffer and return the mean of the samples it holds."""
function _window_mean!(buf::Vector{Float64}, n_seen::Int, sample::Float64)
    buf[mod1(n_seen, length(buf))] = sample
    n = min(n_seen, length(buf))
    acc = 0.0
    @inbounds for i in 1:n
        acc += buf[i]
    end
    return acc / n
end

function _policy_index(policy, esn0_db::Float64)
    return select_mcs(policy, esn0_db)
end

@doc raw"""
    simulate_link(esn0_db::Real, n_blocks::Integer; kwargs...) -> LinkReport

One AWGN transport-block loop.

# Chain
Payload bits, CRC-16, encode, modulate, AWGN, soft demodulation, decode, CRC. A CRC failure at `max_tx = 1` drops the block. With `max_tx > 1` the same coded symbols are sent again and the per-bit LLRs are added (Chase combining) before another decode. The first CRC success stops the repeats. A block that still fails is discarded: its payload does not count as delivered.

# Arguments
- `esn0_db`: ``E_s/N_0`` in dB, with ``E_s = 1``. Finite or ``+\infty``. The call into [`awgn`](@ref) is `awgn(symbols, esn0_db; energy_per_bit = 1)`, so

```math
\sigma^2 = \frac{N_0}{2} = \frac{E_s}{2\,E_s/N_0}.
```

  Information-bit ``E_b/N_0`` is this ratio divided by the MCS spectral efficiency, because one payload bit occupies ``1/\eta`` symbols. The noise calibration matches [`demodulate_soft`](@ref).
- `n_blocks`: number of transport blocks. Each block draws a fresh payload with `rand(0:1, payload_bits)` and fresh noise through `awgn`. Both use the global RNG.

# Keywords
- `table`: MCS list, default [`teaching_mcs_table`](@ref).
- `mcs`: 1-based row to force. `nothing` (default) lets `policy` choose.
- `policy`: [`ThresholdAMC`](@ref) or [`OuterLoopAMC`](@ref). The default is `ThresholdAMC(teaching_amc_thresholds())`, which must match `table`. Ignored when `mcs` is set, and then an outer-loop offset is left unchanged.
- `max_tx`: transmissions of one block, including the first. `1` disables HARQ. Chase combining is the only HARQ mode: incremental redundancy would need puncturing, which this loop does not do.
- `approx`: `:exact` (default) or `:maxlog`, forwarded to [`demodulate_soft`](@ref). On BPSK and Gray QPSK the two agree.
- `ldpc_max_iter`, `ldpc_algorithm`: forwarded to [`ldpc_decode`](@ref). Convolutional rows always use soft-input Viterbi.
- `channel_quality`: `:genie` passes `esn0_db` to the policy. `:moment` passes a sliding mean of [`estimate_esn0_db`](@ref) measured on the **previous** block's first transmission (causal). The first block uses `initial_esn0_db`, or `esn0_db` when that keyword is `nothing`. Passing `initial_esn0_db` together with `:genie` is an error.
- `snr_window`: number of past moment estimates averaged in linear ``E_s/N_0``. Used only for `:moment`.

Transmit energy stays ``E_s = 1``. A power-control loop would scale the symbols before `awgn`; this teaching link does not.

# Combining
Attempt ``t`` observes the same coded bits in independent noise. Bit LLRs are summed,

```math
L_j^{(r)} = \sum_{t=1}^{r} L_j\!\left(y_j^{(t)}\right).
```

For a true AWGN bit LLR this is maximum-likelihood code combining of identical packets (Chase, IEEE Trans. Commun., 33(5):385–393, 1985). BPSK and Gray QPSK LLRs are linear in the observation, so the sum matches symbol-level MRC. Square-QAM LLRs are not linear; the sum is the bit-metric Chase receiver, not joint ML over the repeated constellation.

# References
CRC: ITU-T V.41 polynomial, systematic register as in [`crc16_ccitt`](@ref). Convolutional code and Viterbi: Proakis and Salehi, 5th ed., §8.2. LDPC: the normalised min-sum of [`ldpc_decode`](@ref). Switching thresholds: Goldsmith, 2005, §9.3. Outer-loop step ratio: Sampath, Kumar, and Holtzman, Proc. IEEE VTC, 1997, pp. 929–933.
"""
function simulate_link(esn0_db::Real, n_blocks::Integer;
                       table::AbstractVector{MCS}=teaching_mcs_table(),
                       mcs::Union{Nothing,Integer}=nothing,
                       policy::Union{Nothing,ThresholdAMC,OuterLoopAMC}=nothing,
                       max_tx::Integer=1,
                       approx::Symbol=:exact,
                       ldpc_max_iter::Integer=20,
                       ldpc_algorithm::Symbol=:normalized_min_sum,
                       channel_quality::Symbol=:genie,
                       initial_esn0_db::Union{Nothing,Real}=nothing,
                       snr_window::Integer=1)
    snr = float(esn0_db)
    (snr == Inf || isfinite(snr)) || throw(ArgumentError(
        "Es/N0 must be finite or +Inf, got $esn0_db",
    ))
    n_blocks = Int(n_blocks)
    n_blocks >= 1 || throw(ArgumentError("n_blocks must be ≥ 1, got $n_blocks"))
    max_tx = Int(max_tx)
    max_tx >= 1 || throw(ArgumentError("max_tx must be ≥ 1, got $max_tx"))
    isempty(table) && throw(ArgumentError("MCS table must be non-empty"))
    approx === :exact || approx === :maxlog || throw(ArgumentError(
        "approx must be :exact or :maxlog, got $(repr(approx))",
    ))
    ldpc_max_iter = Int(ldpc_max_iter)
    ldpc_max_iter >= 0 || throw(ArgumentError("ldpc_max_iter must be ≥ 0"))
    ldpc_algorithm in (:sum_product, :min_sum, :normalized_min_sum, :offset_min_sum) ||
        throw(ArgumentError(
            "ldpc_algorithm must be :sum_product, :min_sum, :normalized_min_sum, " *
            "or :offset_min_sum, got $(repr(ldpc_algorithm))",
        ))
    channel_quality === :genie || channel_quality === :moment || throw(ArgumentError(
        "channel_quality must be :genie or :moment, got $(repr(channel_quality))",
    ))
    snr_window = Int(snr_window)
    snr_window >= 1 || throw(ArgumentError("snr_window must be ≥ 1, got $snr_window"))
    if mcs === nothing
        if policy === nothing
            policy = ThresholdAMC(teaching_amc_thresholds())
        end
        length(policy.thresholds_db) == length(table) || throw(ArgumentError(
            "policy has $(length(policy.thresholds_db)) thresholds for a table of $(length(table))",
        ))
    else
        mcs = Int(mcs)
        1 <= mcs <= length(table) || throw(ArgumentError(
            "mcs index must lie in 1:$(length(table)), got $mcs",
        ))
    end
    if channel_quality === :genie && initial_esn0_db !== nothing
        throw(ArgumentError("initial_esn0_db applies only when channel_quality is :moment"))
    end
    if initial_esn0_db === nothing
        initial_q = snr
    else
        initial_q = float(initial_esn0_db)
        (initial_q == Inf || isfinite(initial_q)) || throw(ArgumentError(
            "initial_esn0_db must be finite or +Inf, got $initial_esn0_db",
        ))
    end

    n_mcs = length(table)
    histogram = zeros(Int, n_mcs)
    names = [row.name for row in table]
    n_ack = 0
    n_delivered = 0
    n_success_bits = 0
    n_bit_errors = 0
    n_payload_bits = 0
    n_channel_uses = 0
    n_transmissions = 0
    goodput_sum = 0.0
    mcs_se_sum = 0.0
    quality_db = initial_q
    window = fill(0.0, snr_window)
    n_seen = 0

    for _block in 1:n_blocks
        if mcs === nothing
            # :genie reports the simulated Es/N0. :moment reports the sliding
            # estimate, which `quality_db` holds from the previous block.
            q_db = channel_quality === :genie ? snr : quality_db
            idx = _policy_index(policy, q_db)
        else
            idx = mcs
        end
        row = table[idx]
        histogram[idx] += 1
        mcs_se_sum += row.spectral_efficiency
        payload = rand(0:1, row.payload_bits)
        info = crc_append(payload)
        coded = _encode(row, info)
        symbols = modulate(coded, row.scheme)
        acc = zeros(Float64, row.n_coded)
        decoded = Int[]
        ack = false
        n_tx = 0
        first_rx = symbols
        for tx in 1:max_tx
            n_tx = tx
            # Es stays 1. Power control is not part of this loop: it would scale
            # `symbols` before the channel. Incremental redundancy is not part of
            # it either: a retransmission repeats the same coded bits.
            rx = awgn(symbols, snr; energy_per_bit=1.0)
            if tx == 1
                first_rx = rx
            end
            acc .+= _channel_llr(rx, snr, row.scheme, approx)
            decoded = _decode_info(row, acc, ldpc_max_iter, ldpc_algorithm)
            if length(decoded) == row.n_encoder_in && crc_check(decoded)
                ack = true
                break
            end
        end
        if channel_quality === :moment
            est_db = estimate_esn0_db(first_rx, row.scheme)
            n_seen += 1
            sample = est_db == Inf ? Inf : snr_db_to_linear(est_db)
            mean_lin = _window_mean!(window, n_seen, sample)
            quality_db = mean_lin == Inf ? Inf : 10 * log10(mean_lin)
        end
        if mcs === nothing && policy isa OuterLoopAMC
            observe_acknack!(policy, ack)
        end
        errors = _payload_errors(payload, decoded, row.n_encoder_in)
        delivered = ack && errors == 0
        uses = n_tx * row.n_symbols
        n_ack += ack
        n_delivered += delivered
        n_success_bits += delivered ? row.payload_bits : 0
        n_bit_errors += errors
        n_payload_bits += row.payload_bits
        n_channel_uses += uses
        n_transmissions += n_tx
        goodput_sum += (delivered ? row.payload_bits : 0) / uses
    end

    return LinkReport(
        snr, n_blocks, n_ack, n_delivered, n_ack - n_delivered,
        n_success_bits, n_bit_errors, n_payload_bits,
        n_channel_uses, n_transmissions,
        n_bit_errors / n_payload_bits,
        (n_blocks - n_ack) / n_blocks,
        n_success_bits / n_channel_uses,
        goodput_sum / n_blocks,
        mcs_se_sum / n_blocks,
        n_transmissions / n_blocks,
        histogram, names,
    )
end

