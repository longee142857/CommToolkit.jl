@doc raw"""
    CRC16_CCITT_POLY

`0x1021`, the degree-16 coefficients of

```math
g(x) = x^{16} + x^{12} + x^5 + 1.
```

This is the CRC-CCITT polynomial (ITU-T Recommendation V.41). [`crc16_ccitt`](@ref) uses it as a systematic cyclic check: register initialised to 0, bits processed high degree first, no reflection, xor-out 0. That parameter set is the one often called CRC-16/XMODEM. It is not the reflected CRC-16/KERMIT register and not the `0xFFFF` preset of CRC-16/CCITT-FALSE.
"""
const CRC16_CCITT_POLY = 0x1021

@doc raw"""
    crc16_ccitt(bits::AbstractVector{<:Integer}) -> UInt16

Remainder of ``x^{16} m(x)`` modulo [`CRC16_CCITT_POLY`](@ref).

`bits` are coefficients of ``m(x)`` in ``\{0,1\}``, index 1 being the highest degree. An empty vector has remainder 0. The same call on [`crc_append`](@ref)`(bits)` returns 0, because the appended remainder makes the word a codeword of the cyclic code (Peterson and Brown, Proc. IRE, 49(1):228–235, 1961; Lin and Costello, *Error Control Coding*, 2nd ed., Chapter 4).

The ASCII bytes of `"123456789"`, each byte sent MSB first, have remainder `0x31C3`.
"""
function crc16_ccitt(bits::AbstractVector{<:Integer})
    crc = 0x0000
    @inbounds for b in bits
        (b == 0 || b == 1) || throw(ArgumentError("CRC bits must be 0 or 1, got $b"))
        mix = ((crc >> 15) ⊻ UInt16(b)) & 0x0001
        crc = (crc << 1) & 0xffff
        if mix == 1
            crc ⊻= CRC16_CCITT_POLY
        end
    end
    return crc % UInt16
end

@doc raw"""
    crc_append(bits::AbstractVector{<:Integer}) -> Vector{Int}

Append the 16 remainder bits of [`crc16_ccitt`](@ref), highest degree first.

The result has length `length(bits) + 16` and remainder 0. Entries of `bits` must be 0 or 1.
"""
function crc_append(bits::AbstractVector{<:Integer})
    remainder = crc16_ccitt(bits)
    out = Vector{Int}(undef, length(bits) + 16)
    @inbounds for i in eachindex(bits)
        b = bits[i]
        (b == 0 || b == 1) || throw(ArgumentError("CRC bits must be 0 or 1, got $b"))
        out[i] = Int(b)
    end
    @inbounds for i in 0:15
        out[length(bits) + 1 + i] = Int((remainder >> (15 - i)) & 0x0001)
    end
    return out
end

@doc raw"""
    crc_check(bits::AbstractVector{<:Integer}) -> Bool

`true` when `bits` has length at least 16 and [`crc16_ccitt`](@ref)`(bits)` is 0.

`g(1) = 0`, so every odd-weight error is detected. Even-weight errors in the ideal generated by ``g(x)`` are not. A one-bit flip of a codeword is therefore detected; a shift of ``g(x)`` itself is not (Lin and Costello, 2nd ed., Chapter 4).
"""
function crc_check(bits::AbstractVector{<:Integer})
    length(bits) >= 16 || throw(ArgumentError(
        "CRC-16 codeword must have length ≥ 16, got $(length(bits))",
    ))
    return crc16_ccitt(bits) == 0x0000
end

@doc raw"""
    MCS

One teaching modulation-and-coding entry. Not an NR MCS row.

# Fields
- `name`: short label.
- `scheme`: [`BPSK`](@ref), [`QPSK`](@ref), or square [`QAM`](@ref). Symbol energy is 1.
- `family`: `:convolutional` (the terminated ``K=3`` code) or `:ldpc`.
- `payload_bits`: information bits carried in one transport block, before the CRC.
- `crc_bits`: 16. The encoder input is `payload_bits + crc_bits`.
- `n_encoder_in`: encoder input length. The convolutional tail is not part of this word.
- `n_coded`: bits actually modulated. For a punctured convolutional row this is the length after [`puncture`](@ref), not the mother length.
- `n_symbols`: `n_coded / bits_per_symbol(scheme)`.
- `spectral_efficiency`: `payload_bits / n_symbols`, information bits per symbol on one transmission. CRC bits and the convolutional tail are overhead, not information.
- `ldpc`: the code when `family === :ldpc`, otherwise `nothing`.
- `rate`: `1//2`, `2//3`, or `3//4` for a convolutional row. `nothing` for LDPC. `1//2` is the unpunctured mother code.
- `n_mother`: coded length before puncturing. Equal to `n_coded` for LDPC and for rate 1/2.

Build entries with [`mcs_convolutional`](@ref) or [`mcs_ldpc`](@ref). The unpunctured list is [`teaching_mcs_table`](@ref). The rate list is [`teaching_punctured_mcs_table`](@ref).
"""
struct MCS
    name::String
    scheme::ModulationScheme
    family::Symbol
    payload_bits::Int
    crc_bits::Int
    n_encoder_in::Int
    n_coded::Int
    n_symbols::Int
    spectral_efficiency::Float64
    ldpc::Union{Nothing,LDPCCode}
    rate::Union{Nothing,Rational{Int}}
    n_mother::Int

    function MCS(name::AbstractString, scheme::ModulationScheme, family::Symbol,
                 payload_bits::Int, n_coded::Int, ldpc::Union{Nothing,LDPCCode};
                 rate::Union{Nothing,Rational{Int}}=nothing, n_mother::Int=-1)
        payload_bits >= 1 || throw(ArgumentError(
            "payload_bits must be ≥ 1, got $payload_bits",
        ))
        family === :convolutional || family === :ldpc || throw(ArgumentError(
            "family must be :convolutional or :ldpc, got $(repr(family))",
        ))
        if family === :ldpc
            ldpc isa LDPCCode || throw(ArgumentError("an LDPC MCS needs an LDPCCode"))
            rate === nothing || throw(ArgumentError(
                "an LDPC MCS has no convolutional puncture rate",
            ))
            n_coded == ldpc.n || throw(ArgumentError(
                "n_coded must equal the LDPC block length $(ldpc.n)",
            ))
            payload_bits + 16 == ldpc.k || throw(ArgumentError(
                "payload plus CRC-16 must fill the LDPC information word, got $(payload_bits + 16) and k=$(ldpc.k)",
            ))
            if n_mother != -1 && n_mother != n_coded
                throw(ArgumentError(
                    "LDPC mother length must equal the block length $n_coded, got $n_mother",
                ))
            end
            n_mother = n_coded
        else
            ldpc === nothing || throw(ArgumentError("a convolutional MCS has no LDPC code"))
            if rate === nothing
                rate = 1//2
            end
            (rate == 1//2 || rate == 2//3 || rate == 3//4) || throw(ArgumentError(
                "convolutional rate must be 1//2, 2//3, or 3//4, got $rate",
            ))
            mother_bits = conv_encode(zeros(Int, payload_bits + 16))
            expected_mother = length(mother_bits)
            if n_mother == -1
                n_mother = expected_mother
            end
            n_mother == expected_mother || throw(ArgumentError(
                "convolutional mother length must be $expected_mother, got $n_mother",
            ))
            period = length(puncture_mask(rate))
            n_mother % period == 0 || throw(ArgumentError(
                "mother length $n_mother is not a multiple of the $rate puncture period $period",
            ))
            expected_tx = rate == 1//2 ? n_mother : length(puncture(mother_bits, rate))
            n_coded == expected_tx || throw(ArgumentError(
                "convolutional transmitted length must be $expected_tx, got $n_coded",
            ))
        end
        bps = bits_per_symbol(scheme)
        n_coded % bps == 0 || throw(ArgumentError(
            "coded length $n_coded is not divisible by $bps bits/symbol",
        ))
        n_sym = n_coded ÷ bps
        n_sym >= 1 || throw(ArgumentError("MCS produces no symbols"))
        se = payload_bits / n_sym
        crc_bits = 16
        n_in = payload_bits + crc_bits
        return new(String(name), scheme, family, payload_bits, crc_bits, n_in,
                   n_coded, n_sym, se, ldpc, rate, n_mother)
    end
end

function Base.show(io::IO, mcs::MCS)
    print(io, "MCS(", mcs.name, ", SE=", round(mcs.spectral_efficiency; digits=4))
    if mcs.rate !== nothing
        print(io, ", rate=", mcs.rate)
    end
    print(io, ")")
    return nothing
end

