# Systematic CRC-16. A positive noiseless LLR stands in for Es/N0 = +∞, because
# demodulate_soft rejects a zero noise variance. The sign is the hard bit.
const _NOISELESS_LLR = 50.0

@doc raw"""
    CRC16_CCITT_POLY

`0x1021`, the degree-16 coefficients of

```math
g(x) = x^{16} + x^{12} + x^5 + 1.
```

This is the CRC-CCITT polynomial (ITU-T Recommendation V.41). [`crc16_ccitt`](@ref) uses it as a systematic cyclic check: register initialised to 0, bits processed high degree first, no reflection, xor-out 0. That parameter set is the one often called CRC-16/XMODEM. It is not the reflected CRC-16/KERMIT register and not the `0xFFFF` preset of CRC-16/CCITT-FALSE.
"""
const CRC16_CCITT_POLY = 0x1021

@doc raw"""
    crc16_ccitt(bits::AbstractVector{<:Integer}) -> UInt16

Remainder of ``x^{16} m(x)`` modulo [`CRC16_CCITT_POLY`](@ref).

`bits` are coefficients of ``m(x)`` in ``\{0,1\}``, index 1 being the highest degree. An empty vector has remainder 0. The same call on [`crc_append`](@ref)`(bits)` returns 0, because the appended remainder makes the word a codeword of the cyclic code (Peterson and Brown, Proc. IRE, 49(1):228–235, 1961; Lin and Costello, *Error Control Coding*, 2nd ed., Chapter 4).

The ASCII bytes of `"123456789"`, each byte sent MSB first, have remainder `0x31C3`.
"""
function crc16_ccitt(bits::AbstractVector{<:Integer})
    crc = 0x0000
    @inbounds for b in bits
        (b == 0 || b == 1) || throw(ArgumentError("CRC bits must be 0 or 1, got $b"))
        mix = ((crc >> 15) ⊻ UInt16(b)) & 0x0001
        crc = (crc << 1) & 0xffff
        if mix == 1
            crc ⊻= CRC16_CCITT_POLY
        end
    end
    return crc % UInt16
end

@doc raw"""
    crc_append(bits::AbstractVector{<:Integer}) -> Vector{Int}

Append the 16 remainder bits of [`crc16_ccitt`](@ref), highest degree first.

The result has length `length(bits) + 16` and remainder 0. Entries of `bits` must be 0 or 1.
"""
function crc_append(bits::AbstractVector{<:Integer})
    remainder = crc16_ccitt(bits)
    out = Vector{Int}(undef, length(bits) + 16)
    @inbounds for i in eachindex(bits)
        b = bits[i]
        (b == 0 || b == 1) || throw(ArgumentError("CRC bits must be 0 or 1, got $b"))
        out[i] = Int(b)
    end
    @inbounds for i in 0:15
        out[length(bits) + 1 + i] = Int((remainder >> (15 - i)) & 0x0001)
    end
    return out
end

@doc raw"""
    crc_check(bits::AbstractVector{<:Integer}) -> Bool

`true` when `bits` has length at least 16 and [`crc16_ccitt`](@ref)`(bits)` is 0.

`g(1) = 0`, so every odd-weight error is detected. Even-weight errors in the ideal generated by ``g(x)`` are not. A one-bit flip of a codeword is therefore detected; a shift of ``g(x)`` itself is not (Lin and Costello, 2nd ed., Chapter 4).
"""
function crc_check(bits::AbstractVector{<:Integer})
    length(bits) >= 16 || throw(ArgumentError(
        "CRC-16 codeword must have length ≥ 16, got $(length(bits))",
    ))
    return crc16_ccitt(bits) == 0x0000
end

@doc raw"""
    MCS

One teaching modulation-and-coding entry. Not an NR MCS row.

# Fields
- `name`: short label.
- `scheme`: [`BPSK`](@ref), [`QPSK`](@ref), or square [`QAM`](@ref). Symbol energy is 1.
- `family`: `:convolutional` (the terminated ``K=3`` code) or `:ldpc`.
- `payload_bits`: information bits carried in one transport block, before the CRC.
- `crc_bits`: 16. The encoder input is `payload_bits + crc_bits`.
- `n_encoder_in`, `n_coded`: encoder input and coded-bit length. The convolutional tail is included.
- `n_symbols`: `n_coded / bits_per_symbol(scheme)`.
- `spectral_efficiency`: `payload_bits / n_symbols`, information bits per symbol on one transmission. CRC bits and the convolutional tail are overhead, not information.
- `ldpc`: the code when `family === :ldpc`, otherwise `nothing`.

Build entries with [`mcs_convolutional`](@ref) or [`mcs_ldpc`](@ref). The fixed list is [`teaching_mcs_table`](@ref).
"""
struct MCS
    name::String
    scheme::ModulationScheme
    family::Symbol
    payload_bits::Int
    crc_bits::Int
    n_encoder_in::Int
    n_coded::Int
    n_symbols::Int
    spectral_efficiency::Float64
    ldpc::Union{Nothing,LDPCCode}

    function MCS(name::AbstractString, scheme::ModulationScheme, family::Symbol,
                 payload_bits::Int, n_coded::Int, ldpc::Union{Nothing,LDPCCode})
        payload_bits >= 1 || throw(ArgumentError(
            "payload_bits must be ≥ 1, got $payload_bits",
        ))
        family === :convolutional || family === :ldpc || throw(ArgumentError(
            "family must be :convolutional or :ldpc, got $(repr(family))",
        ))
        if family === :ldpc
            ldpc isa LDPCCode || throw(ArgumentError("an LDPC MCS needs an LDPCCode"))
            n_coded == ldpc.n || throw(ArgumentError(
                "n_coded must equal the LDPC block length $(ldpc.n)",
            ))
            payload_bits + 16 == ldpc.k || throw(ArgumentError(
                "payload plus CRC-16 must fill the LDPC information word, got $(payload_bits + 16) and k=$(ldpc.k)",
            ))
        else
            ldpc === nothing || throw(ArgumentError("a convolutional MCS has no LDPC code"))
            expected = length(conv_encode(zeros(Int, payload_bits + 16)))
            n_coded == expected || throw(ArgumentError(
                "convolutional coded length must be $expected, got $n_coded",
            ))
        end
        bps = bits_per_symbol(scheme)
        n_coded % bps == 0 || throw(ArgumentError(
            "coded length $n_coded is not divisible by $bps bits/symbol",
        ))
        n_sym = n_coded ÷ bps
        n_sym >= 1 || throw(ArgumentError("MCS produces no symbols"))
        se = payload_bits / n_sym
        crc_bits = 16
        n_in = payload_bits + crc_bits
        return new(String(name), scheme, family, payload_bits, crc_bits, n_in,
                   n_coded, n_sym, se, ldpc)
    end
end

function Base.show(io::IO, mcs::MCS)
    print(io, "MCS(", mcs.name, ", SE=", round(mcs.spectral_efficiency; digits=4), ")")
    return nothing
end

@doc raw"""
    spectral_efficiency(mcs::MCS) -> Float64

Information bits per channel symbol on one transmission of `mcs`. See [`MCS`](@ref).
"""
function spectral_efficiency(mcs::MCS)
    return mcs.spectral_efficiency
end

@doc raw"""
    mcs_convolutional(name, scheme::ModulationScheme, payload_bits::Integer) -> MCS

Terminated ``K = 3``, rate-1/2 convolutional MCS. The encoder input is `payload_bits` plus 16 CRC bits. [`conv_encode`](@ref) adds two zero tail bits, so the coded length is ``2(\texttt{payload\_bits} + 18)``. That length must be divisible by the number of bits per symbol.

The mother rate is ``1/2``. The spectral efficiency is lower, because the CRC and the tail are not payload.
"""
function mcs_convolutional(name::AbstractString, scheme::ModulationScheme, payload_bits::Integer)
    payload_bits = Int(payload_bits)
    payload_bits >= 1 || throw(ArgumentError("payload_bits must be ≥ 1, got $payload_bits"))
    n_in = payload_bits + 16
    n_coded = length(conv_encode(zeros(Int, n_in)))
    return MCS(name, scheme, :convolutional, payload_bits, n_coded, nothing)
end

@doc raw"""
    mcs_ldpc(name, scheme::ModulationScheme, code::LDPCCode) -> MCS

LDPC MCS. The encoder input is a full information word of `code.k` bits: the payload, then 16 CRC bits. Requires `code.k ≥ 17` and `code.n` divisible by the number of bits per symbol.

[`simulate_link`](@ref) decodes this entry with flooding normalised min-sum (`alpha = 0.75`), the default of [`ldpc_decode`](@ref).
"""
function mcs_ldpc(name::AbstractString, scheme::ModulationScheme, code::LDPCCode)
    code.k >= 17 || throw(ArgumentError(
        "LDPC dimension k=$(code.k) cannot hold a payload and a CRC-16",
    ))
    payload = code.k - 16
    return MCS(name, scheme, :ldpc, payload, code.n, code)
end

# One allocation of the array code. `teaching_mcs_table` copies the vector, not the code.
const _TEACHING_TABLE = Ref{Union{Nothing,Vector{MCS}}}(nothing)

function _build_teaching_table()
    # Fan array code, no 4-cycles: n = 88, k = 57 (two redundant checks).
    # Payload 41 bits after CRC-16. QPSK uses 44 symbols, SE = 41/44,
    # which sits between rate-1/2 convolutional QPSK and 16-QAM.
    ldpc = array_ldpc(3, 8, 11)
    # Convolutional payload 48. Coded length 2*(48+16+2) = 132, which splits
    # evenly into BPSK, QPSK, 16-QAM, and 64-QAM symbols.
    table = MCS[
        mcs_convolutional("BPSK-conv-1/2", BPSK(), 48),
        mcs_convolutional("QPSK-conv-1/2", QPSK(), 48),
        mcs_ldpc("QPSK-array-LDPC", QPSK(), ldpc),
        mcs_convolutional("16QAM-conv-1/2", QAM(16), 48),
        mcs_convolutional("64QAM-conv-1/2", QAM(64), 48),
    ]
    for i in 2:length(table)
        table[i].spectral_efficiency > table[i - 1].spectral_efficiency ||
            error("internal: teaching MCS table is not strictly increasing in SE")
    end
    return table
end

@doc raw"""
    teaching_mcs_table() -> Vector{MCS}

Five teaching MCS rows, ordered by increasing spectral efficiency. Not an NR CQI/MCS table.

| Name | Modulation | Code | Payload | Symbols | SE (bit/symbol) |
|---|---|---|---|---|---|
| BPSK-conv-1/2 | BPSK | terminated (7, 5) | 48 | 132 | ``48/132`` |
| QPSK-conv-1/2 | QPSK | terminated (7, 5) | 48 | 66 | ``48/66`` |
| QPSK-array-LDPC | QPSK | `array_ldpc(3, 8, 11)`, ``k=57`` | 41 | 44 | ``41/44`` |
| 16QAM-conv-1/2 | 16-QAM | terminated (7, 5) | 48 | 33 | ``48/33`` |
| 64QAM-conv-1/2 | 64-QAM | terminated (7, 5) | 48 | 22 | ``48/22`` |

SE counts payload bits only. Each row pays 16 CRC bits. Convolutional rows also pay two tail bits. The LDPC row is Fan's array code (no 4-cycles; ``H`` is ``33 \times 88`` with rank 31); the link decodes it with normalised min-sum. Switching thresholds for this list are [`teaching_amc_thresholds`](@ref).
"""
function teaching_mcs_table()
    if _TEACHING_TABLE[] === nothing
        _TEACHING_TABLE[] = _build_teaching_table()
    end
    return copy(_TEACHING_TABLE[])
end

@doc raw"""
    ThresholdAMC

Pick the highest-index MCS whose threshold is at most the reported ``E_s/N_0``.

# Fields
- `thresholds_db`: length equal to the MCS table, non-decreasing, in dB. `+Inf` disables that row and every row the scan would only reach after it. `NaN` is rejected. MCS 1 is the fallback when the report lies below every threshold.

The rule is the textbook switching threshold (Goldsmith, *Wireless Communications*, Cambridge University Press, 2005, §9.3): use the fastest row that the current channel quality supports. [`teaching_amc_thresholds`](@ref) places those edges where fixed-MCS throughputs cross on this table.
"""
struct ThresholdAMC
    thresholds_db::Vector{Float64}

    function ThresholdAMC(thresholds_db::AbstractVector{<:Real})
        isempty(thresholds_db) && throw(ArgumentError("thresholds must be non-empty"))
        th = Vector{Float64}(undef, length(thresholds_db))
        @inbounds for i in eachindex(thresholds_db)
            x = float(thresholds_db[i])
            isnan(x) && throw(ArgumentError("thresholds must not be NaN"))
            th[i] = x
        end
        for i in 2:length(th)
            th[i] >= th[i - 1] || throw(ArgumentError(
                "thresholds must be non-decreasing, got $(th[i - 1]) then $(th[i])",
            ))
        end
        return new(th)
    end
end

@doc raw"""
    OuterLoopAMC

[`ThresholdAMC`](@ref) driven by ``E_s/N_0 - \texttt{offset\_db}``, with the offset walked by CRC outcomes.

# Fields
- `thresholds_db`: same convention as [`ThresholdAMC`](@ref).
- `target_bler`: desired CRC failure rate, in ``(0, 1)``.
- `offset_db`: current backoff, in dB. Updated in place by [`observe_acknack!`](@ref).
- `step_up_db`: subtracted from the offset on CRC ACK. Finite and positive.
- `step_down_db`: added to the offset on CRC NACK. The constructor sets it to `step_up_db * (1 - target_bler) / target_bler`, the step ratio that holds the target as an equilibrium (Sampath, Kumar, and Holtzman, Proc. IEEE VTC, 1997, pp. 929–933). This implementation moves an MCS threshold offset, not a transmit power.
- `min_offset_db`, `max_offset_db`: clamp.

[`simulate_link`](@ref) calls [`observe_acknack!`](@ref) only when this policy is choosing the MCS. A fixed `mcs` index does not move the offset. There is no per-process HARQ state and no NR outer loop.
"""
mutable struct OuterLoopAMC
    thresholds_db::Vector{Float64}
    target_bler::Float64
    offset_db::Float64
    step_up_db::Float64
    step_down_db::Float64
    min_offset_db::Float64
    max_offset_db::Float64

    function OuterLoopAMC(thresholds_db::AbstractVector{<:Real};
                          target_bler::Real=0.1,
                          offset_db::Real=0.0,
                          step_db::Real=0.5,
                          min_offset_db::Real=-15.0,
                          max_offset_db::Real=30.0)
        base = ThresholdAMC(thresholds_db)
        (isfinite(target_bler) && 0 < target_bler < 1) || throw(ArgumentError(
            "target_bler must lie in (0, 1), got $target_bler",
        ))
        (isfinite(step_db) && step_db > 0) || throw(ArgumentError(
            "step_db must be finite and positive, got $step_db",
        ))
        isfinite(offset_db) || throw(ArgumentError("offset_db must be finite, got $offset_db"))
        isfinite(min_offset_db) && isfinite(max_offset_db) || throw(ArgumentError(
            "offset clamps must be finite",
        ))
        min_offset_db < max_offset_db || throw(ArgumentError(
            "min_offset_db must be < max_offset_db",
        ))
        step_down = step_db * (1 - float(target_bler)) / float(target_bler)
        offset = clamp(float(offset_db), float(min_offset_db), float(max_offset_db))
        return new(base.thresholds_db, float(target_bler), offset, float(step_db),
                   step_down, float(min_offset_db), float(max_offset_db))
    end
end

function Base.show(io::IO, policy::ThresholdAMC)
    print(io, "ThresholdAMC(", policy.thresholds_db, ")")
    return nothing
end

function Base.show(io::IO, policy::OuterLoopAMC)
    print(io, "OuterLoopAMC(target=", policy.target_bler,
          ", offset=", policy.offset_db, " dB)")
    return nothing
end

@doc raw"""
    select_mcs(policy::ThresholdAMC, esn0_db::Real) -> Int
    select_mcs(policy::OuterLoopAMC, esn0_db::Real) -> Int

1-based MCS index. `esn0_db` is ``E_s/N_0`` in dB, finite or ``+\infty``. The outer-loop method subtracts `policy.offset_db` first.

The scan keeps the highest index whose threshold is `≤ esn0_db`. If a row is dominated, give it the same threshold as the next row: the higher index wins the tie, and the dominated row is never chosen.
"""
function select_mcs(policy::ThresholdAMC, esn0_db::Real)
    snr = float(esn0_db)
    (snr == Inf || isfinite(snr)) || throw(ArgumentError(
        "Es/N0 must be finite or +Inf, got $esn0_db",
    ))
    th = policy.thresholds_db
    idx = 1
    @inbounds for i in eachindex(th)
        if snr >= th[i]
            idx = i
        else
            break
        end
    end
    return idx
end

function select_mcs(policy::OuterLoopAMC, esn0_db::Real)
    return select_mcs(ThresholdAMC(policy.thresholds_db), float(esn0_db) - policy.offset_db)
end

@doc raw"""
    observe_acknack!(policy::OuterLoopAMC, ack::Bool) -> Float64

ACK subtracts `step_up_db` from the offset. NACK adds `step_down_db`. The result is clamped to `[min_offset_db, max_offset_db]` and stored in `policy.offset_db`.
"""
function observe_acknack!(policy::OuterLoopAMC, ack::Bool)
    if ack
        policy.offset_db -= policy.step_up_db
    else
        policy.offset_db += policy.step_down_db
    end
    policy.offset_db = clamp(policy.offset_db, policy.min_offset_db, policy.max_offset_db)
    return policy.offset_db
end

@doc raw"""
    teaching_amc_thresholds() -> Vector{Float64}

``E_s/N_0`` switching thresholds, in dB, for [`teaching_mcs_table`](@ref), lowest MCS first.

The first entry is ``-\infty``. Each later entry is the left edge of the integer-dB bins on which that row had the highest fixed-MCS throughput (no HARQ) in a design sweep: Julia 1.10.12, global seed `0x0c0de1162`, 80 transport blocks, `approx = :exact`, LDPC `max_iter = 20`, integer ``E_s/N_0`` from 0 dB through 18 dB. On that sample the winners were BPSK-conv at 0–1 dB, QPSK-conv at 2 dB, QPSK-array-LDPC at 3–6 dB, 16QAM-conv at 7–10 dB, and 64QAM-conv from 11 dB. The closest calls were 3 dB (LDPC 0.687 bit/use against QPSK-conv 0.645) and 11 dB (64QAM-conv 1.555 against 16QAM-conv 1.455). A different `randn` stream can move those two edges by about 1 dB; the other edges have a much wider gap. Tests therefore use 0 dB, 5 dB, and 16 dB, not the crossings.

These numbers belong to this payload, CRC, and code list. They are not NR CQI thresholds and they are not recomputed at run time.
"""
function teaching_amc_thresholds()
    # Julia 1.10.12, seed 0x0c0de1162, 80 blocks, no HARQ. See the docstring.
    return [-Inf, 2.0, 3.0, 7.0, 11.0]
end

@doc raw"""
    estimate_esn0_db(symbols, scheme::ModulationScheme) -> Float64

Second-moment estimate of ``E_s/N_0`` in dB, assuming the unit-energy constellation of `scheme`.

A complex symbol has ``\mathbb{E}[|y|^2] = E_s + N_0``. Real BPSK from [`modulate`](@ref) / [`awgn`](@ref) has one real noise component, ``\sigma^2 = N_0/2``, so ``\mathbb{E}[y^2] = E_s + N_0/2``. The estimate returns ``+\infty`` when the implied noise power is not positive (a short or noiseless record). It is a teaching estimator, not a pilot measurement.
"""
function estimate_esn0_db(symbols::AbstractVector{<:Number}, scheme::ModulationScheme)
    n = length(symbols)
    n >= 1 || throw(ArgumentError("need at least one symbol to estimate Es/N0"))
    power = sum(abs2, symbols) / n
    # Real BPSK: E[y^2] = 1 + σ² and σ² = N0/2, so N0 = 2(E[y^2] - 1).
    # Complex: E[|y|^2] = 1 + N0.
    n0 = scheme isa BPSK && !(eltype(symbols) <: Complex) ? 2 * (power - 1) : power - 1
    n0 > 0 || return Inf
    return -10 * log10(n0)
end

@doc raw"""
    LinkReport

Counts and rates from one [`simulate_link`](@ref) call.

# Fields
- `esn0_db`: the AWGN ``E_s/N_0`` that was simulated, in dB.
- `n_blocks`: transport blocks offered.
- `n_ack`: blocks whose final decoder word passed the CRC.
- `n_delivered`: blocks with a CRC ACK and a genie-correct payload. An undetected CRC error is an ACK but is not delivered.
- `n_undetected`: `n_ack - n_delivered`.
- `n_success_bits`: payload bits in delivered blocks. CRC bits are not included. A CRC failure discards the block even if the payload happened to be correct.
- `n_bit_errors`, `n_payload_bits`: genie payload mismatches of the **last** decode of each block, and the number of payload bits compared. `ber = n_bit_errors / n_payload_bits`. CRC bits are not in this rate.
- `n_channel_uses`: modulated symbols actually sent, including Chase retransmissions.
- `n_transmissions`: same sum, counted in transport-block transmissions. `mean_transmissions = n_transmissions / n_blocks`.
- `bler`: `(n_blocks - n_ack) / n_blocks`. Residual CRC failure rate after HARQ.
- `throughput`: `n_success_bits / n_channel_uses`. Delivered information bits per channel use. One channel use is one complex baseband symbol (real BPSK is one symbol as well).
- `spectral_efficiency`: mean over blocks of (delivered payload bits of that block) / (symbols used by that block). This equals `throughput` when every block spends the same number of symbols. With mixed MCS rows or a random number of retransmissions the ratio-of-sums and the mean-of-ratios differ.
- `mean_mcs_efficiency`: mean of the selected row's design [`spectral_efficiency`](@ref), before CRC failures and retransmissions.
- `mcs_histogram`: how many blocks selected each row, index 1 first.
- `mcs_names`: copy of the table names, same order as the histogram.

At symbol rate 1 and Nyquist bandwidth 1 Hz, `throughput` is the realised spectral efficiency in bit/s/Hz. The field `spectral_efficiency` is the per-block average of that same ratio.
"""
struct LinkReport
    esn0_db::Float64
    n_blocks::Int
    n_ack::Int
    n_delivered::Int
    n_undetected::Int
    n_success_bits::Int
    n_bit_errors::Int
    n_payload_bits::Int
    n_channel_uses::Int
    n_transmissions::Int
    ber::Float64
    bler::Float64
    throughput::Float64
    spectral_efficiency::Float64
    mean_mcs_efficiency::Float64
    mean_transmissions::Float64
    mcs_histogram::Vector{Int}
    mcs_names::Vector{String}
end

