@doc raw"""
    ThresholdAMC

Pick the highest-index MCS whose threshold is at most the reported ``E_s/N_0``.

# Fields
- `thresholds_db`: length equal to the MCS table, non-decreasing, in dB. `+Inf` disables that row and every row the scan would only reach after it. `NaN` is rejected. MCS 1 is the fallback when the report lies below every threshold.

The rule is the textbook switching threshold (Goldsmith, *Wireless Communications*, Cambridge University Press, 2005, §9.3): use the fastest row that the current channel quality supports. [`teaching_amc_thresholds`](@ref) places those edges where fixed-MCS throughputs cross on this table.
"""
struct ThresholdAMC
    thresholds_db::Vector{Float64}

    function ThresholdAMC(thresholds_db::AbstractVector{<:Real})
        isempty(thresholds_db) && throw(ArgumentError("thresholds must be non-empty"))
        th = Vector{Float64}(undef, length(thresholds_db))
        @inbounds for i in eachindex(thresholds_db)
            x = float(thresholds_db[i])
            isnan(x) && throw(ArgumentError("thresholds must not be NaN"))
            th[i] = x
        end
        for i in 2:length(th)
            th[i] >= th[i - 1] || throw(ArgumentError(
                "thresholds must be non-decreasing, got $(th[i - 1]) then $(th[i])",
            ))
        end
        return new(th)
    end
end

@doc raw"""
    OuterLoopAMC

[`ThresholdAMC`](@ref) driven by ``E_s/N_0 - \texttt{offset\_db}``, with the offset walked by CRC outcomes.

# Fields
- `thresholds_db`: same convention as [`ThresholdAMC`](@ref).
- `target_bler`: desired CRC failure rate, in ``(0, 1)``.
- `offset_db`: current backoff, in dB. Updated in place by [`observe_acknack!`](@ref).
- `step_up_db`: subtracted from the offset on CRC ACK. Finite and positive.
- `step_down_db`: added to the offset on CRC NACK. The constructor sets it to `step_up_db * (1 - target_bler) / target_bler`, the step ratio that holds the target as an equilibrium (Sampath, Kumar, and Holtzman, Proc. IEEE VTC, 1997, pp. 929–933). This implementation moves an MCS threshold offset, not a transmit power.
- `min_offset_db`, `max_offset_db`: clamp.

[`simulate_link`](@ref) calls [`observe_acknack!`](@ref) only when this policy is choosing the MCS. A fixed `mcs` index does not move the offset. There is no per-process HARQ state and no NR outer loop.
"""
mutable struct OuterLoopAMC
    thresholds_db::Vector{Float64}
    target_bler::Float64
    offset_db::Float64
    step_up_db::Float64
    step_down_db::Float64
    min_offset_db::Float64
    max_offset_db::Float64

    function OuterLoopAMC(thresholds_db::AbstractVector{<:Real};
                          target_bler::Real=0.1,
                          offset_db::Real=0.0,
                          step_db::Real=0.5,
                          min_offset_db::Real=-15.0,
                          max_offset_db::Real=30.0)
        base = ThresholdAMC(thresholds_db)
        (isfinite(target_bler) && 0 < target_bler < 1) || throw(ArgumentError(
            "target_bler must lie in (0, 1), got $target_bler",
        ))
        (isfinite(step_db) && step_db > 0) || throw(ArgumentError(
            "step_db must be finite and positive, got $step_db",
        ))
        isfinite(offset_db) || throw(ArgumentError("offset_db must be finite, got $offset_db"))
        isfinite(min_offset_db) && isfinite(max_offset_db) || throw(ArgumentError(
            "offset clamps must be finite",
        ))
        min_offset_db < max_offset_db || throw(ArgumentError(
            "min_offset_db must be < max_offset_db",
        ))
        step_down = step_db * (1 - float(target_bler)) / float(target_bler)
        offset = clamp(float(offset_db), float(min_offset_db), float(max_offset_db))
        return new(base.thresholds_db, float(target_bler), offset, float(step_db),
                   step_down, float(min_offset_db), float(max_offset_db))
    end
end

function Base.show(io::IO, policy::ThresholdAMC)
    print(io, "ThresholdAMC(", policy.thresholds_db, ")")
    return nothing
end

function Base.show(io::IO, policy::OuterLoopAMC)
    print(io, "OuterLoopAMC(target=", policy.target_bler,
          ", offset=", policy.offset_db, " dB)")
    return nothing
end

@doc raw"""
    select_mcs(policy::ThresholdAMC, esn0_db::Real) -> Int
    select_mcs(policy::OuterLoopAMC, esn0_db::Real) -> Int

1-based MCS index. `esn0_db` is ``E_s/N_0`` in dB, finite or ``+\infty``. The outer-loop method subtracts `policy.offset_db` first.

The scan keeps the highest index whose threshold is `≤ esn0_db`. If a row is dominated, give it the same threshold as the next row: the higher index wins the tie, and the dominated row is never chosen.
"""
function select_mcs(policy::ThresholdAMC, esn0_db::Real)
    snr = float(esn0_db)
    (snr == Inf || isfinite(snr)) || throw(ArgumentError(
        "Es/N0 must be finite or +Inf, got $esn0_db",
    ))
    th = policy.thresholds_db
    idx = 1
    @inbounds for i in eachindex(th)
        if snr >= th[i]
            idx = i
        else
            break
        end
    end
    return idx
end

function select_mcs(policy::OuterLoopAMC, esn0_db::Real)
    return select_mcs(ThresholdAMC(policy.thresholds_db), float(esn0_db) - policy.offset_db)
end

@doc raw"""
    observe_acknack!(policy::OuterLoopAMC, ack::Bool) -> Float64

ACK subtracts `step_up_db` from the offset. NACK adds `step_down_db`. The result is clamped to `[min_offset_db, max_offset_db]` and stored in `policy.offset_db`.
"""
function observe_acknack!(policy::OuterLoopAMC, ack::Bool)
    if ack
        policy.offset_db -= policy.step_up_db
    else
        policy.offset_db += policy.step_down_db
    end
    policy.offset_db = clamp(policy.offset_db, policy.min_offset_db, policy.max_offset_db)
    return policy.offset_db
end

@doc raw"""
    teaching_amc_thresholds() -> Vector{Float64}

``E_s/N_0`` switching thresholds, in dB, for [`teaching_mcs_table`](@ref), lowest MCS first.

The first entry is ``-\infty``. Each later entry is the left edge of the integer-dB bins on which that row had the highest fixed-MCS throughput (no HARQ) in a design sweep: Julia 1.10.12, global seed `0x0c0de1162`, 80 transport blocks, `approx = :exact`, LDPC `max_iter = 20`, integer ``E_s/N_0`` from 0 dB through 18 dB. On that sample the winners were BPSK-conv at 0–1 dB, QPSK-conv at 2 dB, QPSK-array-LDPC at 3–6 dB, 16QAM-conv at 7–10 dB, and 64QAM-conv from 11 dB. The closest calls were 3 dB (LDPC 0.687 bit/use against QPSK-conv 0.645) and 11 dB (64QAM-conv 1.555 against 16QAM-conv 1.455). A different `randn` stream can move those two edges by about 1 dB; the other edges have a much wider gap. Tests therefore use 0 dB, 5 dB, and 16 dB, not the crossings.

These numbers belong to this payload, CRC, and code list. They are not NR CQI thresholds and they are not recomputed at run time.
"""
function teaching_amc_thresholds()
    # Julia 1.10.12, seed 0x0c0de1162, 80 blocks, no HARQ. See the docstring.
    return [-Inf, 2.0, 3.0, 7.0, 11.0]
end

@doc raw"""
    teaching_punctured_amc_thresholds() -> Vector{Float64}

``E_s/N_0`` switching thresholds, in dB, for [`teaching_punctured_mcs_table`](@ref), lowest MCS first.

The first entry is ``-\infty``. Each later entry is the left edge of the integer-dB bins on which that row had the highest fixed-MCS throughput (no HARQ, `receiver = :viterbi`) in a design sweep: Julia 1.10.12, global seed `0x0c0de1162`, 80 transport blocks, integer ``E_s/N_0`` from −2 dB through 16 dB. On that sample the winners were BPSK-1/2 from −2 dB through 1 dB, QPSK-1/2 at 2–3 dB, QPSK-2/3 at 4–5 dB, QPSK-3/4 at 6–7 dB, and 16QAM-1/2 from 8 dB. The closest calls were 1 dB (BPSK 0.370 bit/use against QPSK-1/2 0.338), 5 dB (QPSK-2/3 0.912 against QPSK-3/4 0.900), and 7 dB (QPSK-3/4 1.125 against 16QAM-1/2 1.087). The same seed on Julia 1.13.2 kept every edge except 5 dB, where QPSK-3/4 was ahead by about 0.002 bit/use. Tests therefore use 0 dB, 3 dB, and 10 dB, not those crossings.

These numbers belong to this payload, CRC, puncture mask, and modulation list. They are not [`teaching_amc_thresholds`](@ref), not NR CQI thresholds, and they are not recomputed at run time.
"""
function teaching_punctured_amc_thresholds()
    # Julia 1.10.12, seed 0x0c0de1162, 80 blocks, no HARQ. See the docstring.
    return [-Inf, 2.0, 4.0, 6.0, 8.0]
end

@doc raw"""
    estimate_esn0_db(symbols, scheme::ModulationScheme) -> Float64

Second-moment estimate of ``E_s/N_0`` in dB, assuming the unit-energy constellation of `scheme`.

A complex symbol has ``\mathbb{E}[|y|^2] = E_s + N_0``. Real BPSK from [`modulate`](@ref) / [`awgn`](@ref) has one real noise component, ``\sigma^2 = N_0/2``, so ``\mathbb{E}[y^2] = E_s + N_0/2``. The estimate returns ``+\infty`` when the implied noise power is not positive (a short or noiseless record). It is a teaching estimator, not a pilot measurement.
"""
function estimate_esn0_db(symbols::AbstractVector{<:Number}, scheme::ModulationScheme)
    n = length(symbols)
    n >= 1 || throw(ArgumentError("need at least one symbol to estimate Es/N0"))
    power = sum(abs2, symbols) / n
    # Real BPSK: E[y^2] = 1 + σ² and σ² = N0/2, so N0 = 2(E[y^2] - 1).
    # Complex: E[|y|^2] = 1 + N0.
    n0 = scheme isa BPSK && !(eltype(symbols) <: Complex) ? 2 * (power - 1) : power - 1
    n0 > 0 || return Inf
    return -10 * log10(n0)
end

@doc raw"""
    LinkReport

Counts and rates from one [`simulate_link`](@ref) call.

# Fields
- `esn0_db`: the AWGN ``E_s/N_0`` that was simulated, in dB.
- `n_blocks`: transport blocks offered.
- `n_ack`: blocks whose final decoder word passed the CRC.
- `n_delivered`: blocks with a CRC ACK and a genie-correct payload. An undetected CRC error is an ACK but is not delivered.
- `n_undetected`: `n_ack - n_delivered`.
- `n_success_bits`: payload bits in delivered blocks. CRC bits are not included. A CRC failure discards the block even if the payload happened to be correct.
- `n_bit_errors`, `n_payload_bits`: genie payload mismatches of the **last** decode of each block, and the number of payload bits compared. `ber = n_bit_errors / n_payload_bits`. CRC bits are not in this rate.
- `n_channel_uses`: modulated symbols actually sent, including HARQ retransmissions. With `harq = :ir` a complementary retransmission is shorter than the first transmission, so this is not `n_transmissions` times one row's symbol count.
- `n_transmissions`: same sum, counted in transport-block transmissions. `mean_transmissions = n_transmissions / n_blocks`.
- `bler`: `(n_blocks - n_ack) / n_blocks`. Residual CRC failure rate after HARQ.
- `throughput`: `n_success_bits / n_channel_uses`. Delivered information bits per channel use. One channel use is one complex baseband symbol (real BPSK is one symbol as well).
- `spectral_efficiency`: mean over blocks of (delivered payload bits of that block) / (symbols used by that block). This equals `throughput` when every block spends the same number of symbols. With mixed MCS rows or a random number of retransmissions the ratio-of-sums and the mean-of-ratios differ.
- `mean_mcs_efficiency`: mean of the selected row's design [`spectral_efficiency`](@ref), before CRC failures and retransmissions.
- `mcs_histogram`: how many blocks selected each row, index 1 first.
- `mcs_names`: copy of the table names, same order as the histogram.

At symbol rate 1 and Nyquist bandwidth 1 Hz, `throughput` is the realised spectral efficiency in bit/s/Hz. The field `spectral_efficiency` is the per-block average of that same ratio.
"""
