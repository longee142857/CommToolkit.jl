@doc raw"""
    mcs_convolutional(name, scheme::ModulationScheme, payload_bits::Integer;
                      rate::Real=1//2) -> MCS

Terminated ``K = 3`` convolutional MCS. The encoder input is `payload_bits` plus 16 CRC bits. [`conv_encode`](@ref) adds two zero tail bits, so the mother length is ``2(\texttt{payload\_bits} + 18)``.

`rate` is `1//2` (default, nothing deleted), `2//3`, or `3//4`. The mask is [`puncture_mask`](@ref), applied to the mother stream with the tail included. The mother length must be a multiple of the mask period, so an MCS row has no partial period. The transmitted length must be divisible by the number of bits per symbol. A floating-point rate is rejected.

The spectral efficiency is payload bits per transmitted symbol. It is lower than `rate` times the bits per symbol, because the CRC and the tail are not payload. This is not an NR MCS index. Chase or incremental-redundancy retransmission behaviour lives in [`simulate_link`](@ref), not in the row.
"""
function mcs_convolutional(name::AbstractString, scheme::ModulationScheme, payload_bits::Integer;
                           rate::Real=1//2)
    payload_bits = Int(payload_bits)
    payload_bits >= 1 || throw(ArgumentError("payload_bits must be ≥ 1, got $payload_bits"))
    rate isa Rational || throw(ArgumentError(
        "rate must be 1//2, 2//3, or 3//4, got $(repr(rate))",
    ))
    rate = Rational{Int}(numerator(rate), denominator(rate))
    n_in = payload_bits + 16
    mother = conv_encode(zeros(Int, n_in))
    n_coded = rate == 1//2 ? length(mother) : length(puncture(mother, rate))
    return MCS(name, scheme, :convolutional, payload_bits, n_coded, nothing;
               rate=rate, n_mother=length(mother))
end

@doc raw"""
    mcs_ldpc(name, scheme::ModulationScheme, code::LDPCCode) -> MCS

LDPC MCS. The encoder input is a full information word of `code.k` bits: the payload, then 16 CRC bits. Requires `code.k ≥ 17` and `code.n` divisible by the number of bits per symbol.

[`simulate_link`](@ref) decodes this entry with flooding normalised min-sum (`alpha = 0.75`), the default of [`ldpc_decode`](@ref).
"""
function mcs_ldpc(name::AbstractString, scheme::ModulationScheme, code::LDPCCode)
    code.k >= 17 || throw(ArgumentError(
        "LDPC dimension k=$(code.k) cannot hold a payload and a CRC-16",
    ))
    payload = code.k - 16
    return MCS(name, scheme, :ldpc, payload, code.n, code)
end

# One allocation of the array code. `teaching_mcs_table` copies the vector, not the code.
const _TEACHING_TABLE = Ref{Union{Nothing,Vector{MCS}}}(nothing)

function _build_teaching_table()
    # Fan array code, no 4-cycles: n = 88, k = 57 (two redundant checks).
    # Payload 41 bits after CRC-16. QPSK uses 44 symbols, SE = 41/44,
    # which sits between rate-1/2 convolutional QPSK and 16-QAM.
    ldpc = array_ldpc(3, 8, 11)
    # Convolutional payload 48. Coded length 2*(48+16+2) = 132, which splits
    # evenly into BPSK, QPSK, 16-QAM, and 64-QAM symbols.
    table = MCS[
        mcs_convolutional("BPSK-conv-1/2", BPSK(), 48),
        mcs_convolutional("QPSK-conv-1/2", QPSK(), 48),
        mcs_ldpc("QPSK-array-LDPC", QPSK(), ldpc),
        mcs_convolutional("16QAM-conv-1/2", QAM(16), 48),
        mcs_convolutional("64QAM-conv-1/2", QAM(64), 48),
    ]
    for i in 2:length(table)
        table[i].spectral_efficiency > table[i - 1].spectral_efficiency ||
            error("internal: teaching MCS table is not strictly increasing in SE")
    end
    return table
end

@doc raw"""
    teaching_mcs_table() -> Vector{MCS}

Five teaching MCS rows, ordered by increasing spectral efficiency. Not an NR CQI/MCS table.

| Name | Modulation | Code | Payload | Symbols | SE (bit/symbol) |
|---|---|---|---|---|---|
| BPSK-conv-1/2 | BPSK | terminated (7, 5) | 48 | 132 | ``48/132`` |
| QPSK-conv-1/2 | QPSK | terminated (7, 5) | 48 | 66 | ``48/66`` |
| QPSK-array-LDPC | QPSK | `array_ldpc(3, 8, 11)`, ``k=57`` | 41 | 44 | ``41/44`` |
| 16QAM-conv-1/2 | 16-QAM | terminated (7, 5) | 48 | 33 | ``48/33`` |
| 64QAM-conv-1/2 | 64-QAM | terminated (7, 5) | 48 | 22 | ``48/22`` |

SE counts payload bits only. Each row pays 16 CRC bits. Convolutional rows also pay two tail bits. The LDPC row is Fan's array code (no 4-cycles; ``H`` is ``33 \times 88`` with rank 31); the link decodes it with normalised min-sum. Switching thresholds for this list are [`teaching_amc_thresholds`](@ref).
"""
function teaching_mcs_table()
    if _TEACHING_TABLE[] === nothing
        _TEACHING_TABLE[] = _build_teaching_table()
    end
    return copy(_TEACHING_TABLE[])
end

# Payload 54. Mother length 2*(54+16+2) = 144, a multiple of the 1/2, 2/3, and 3/4 periods.
const _PUNCTURED_PAYLOAD = 54
const _PUNCTURED_TABLE = Ref{Union{Nothing,Vector{MCS}}}(nothing)

function _build_punctured_table()
    p = _PUNCTURED_PAYLOAD
    table = MCS[
        mcs_convolutional("BPSK-1/2", BPSK(), p; rate=1//2),
        mcs_convolutional("QPSK-1/2", QPSK(), p; rate=1//2),
        mcs_convolutional("QPSK-2/3", QPSK(), p; rate=2//3),
        mcs_convolutional("QPSK-3/4", QPSK(), p; rate=3//4),
        mcs_convolutional("16QAM-1/2", QAM(16), p; rate=1//2),
    ]
    for i in 2:length(table)
        table[i].spectral_efficiency > table[i - 1].spectral_efficiency ||
            error("internal: punctured MCS table is not strictly increasing in SE")
    end
    return table
end

